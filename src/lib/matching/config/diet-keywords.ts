/**
 * Curated keyword lists behind the diet classifier.
 *
 * Every phrase is written in the classifier's match form: lowercase ASCII words separated by single
 * spaces (no hyphens or apostrophes — "goat's cheese" is written "goats cheese", "gluten-free" is
 * "gluten free"). Phrases match on word boundaries and the last word tolerates a plural, so 'egg'
 * also matches "eggs" and 'anchovy' matches "anchovies", but 'egg' never matches "eggplant".
 *
 * The lists are deliberately conservative: when a processed product often contains an ingredient
 * (stock cubes and wheat, Thai curry paste and shrimp, pesto and parmesan) it is listed, because
 * under-claiming "vegan" or "gluten-free" is safe and over-claiming is not.
 */

/** Ingredient categories the diet rules are built from. */
export const DIET_CATEGORIES = ['meat', 'fish', 'dairy', 'egg', 'animal', 'gluten'] as const
export type DietCategory = (typeof DIET_CATEGORIES)[number]

/** Non-empty, so every list compiles to a real pattern. */
export type PhraseList = readonly [string, ...string[]]

export interface CategoryKeywords {
  /** Phrases that put an ingredient in the category. */
  readonly keywords: PhraseList
  /** Phrases blanked out before keywords are matched ('peanut butter' is not butter). */
  readonly exceptions: PhraseList
  /** Modifiers that clear the whole ingredient of the category ('vegan cheese', 'tamari'). */
  readonly neutralizers: PhraseList
}

