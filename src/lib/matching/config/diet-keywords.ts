/**
 * Meat and fish stand-ins. A 'vegetarian' or 'meat free' label promises no meat or fish and nothing
 * more: a vegetarian sausage, veggie burger or meat-free mince is often bound with egg white, holds
 * cheese or is made from wheat or barley (Quorn is). So the labels are MEAT and FISH neutralizers
 * only, and a meat or fish word under one of them (or a stand-in named without one) falls into
 * every one of `categories` unless a vegan, plant-based, egg-free, dairy-free or gluten-free label
 * clears it. 'Vegan sausage' therefore stays vegan; 'vegetarian sausage' is only vegetarian.
 */
